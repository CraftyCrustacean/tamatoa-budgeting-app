package com.example.tamatoa.data

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey

//This file outlined the tables that the database requires
//Information on how each table should be made was found at:
//https://developer.android.com/training/data-storage/room/defining-data
//https://www.youtube.com/watch?v=bOd3wO0uFr8
//https://www.youtube.com/watch?v=sWOmlDvz_3U

@Entity(tableName = "users")
data class UserEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val username: String,
    val password: String,   // Stored as plain text since this is a prototype
    val createdAtMillis: Long = System.currentTimeMillis() //used for achievement tracking
)

@Entity(
    tableName = "categories",
    foreignKeys = [ForeignKey(
        entity = UserEntity::class,
        parentColumns = ["id"],
        childColumns = ["userId"],
        onDelete = ForeignKey.CASCADE
    )],
    indices = [Index("userId")]
)
data class CategoryEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long,
    val name: String,
    val colour: String   //colours are stored as a hex string
)

@Entity(
    tableName = "expenses",
    foreignKeys = [
        ForeignKey(
            entity = UserEntity::class,
            parentColumns = ["id"],
            childColumns = ["userId"],
            onDelete = ForeignKey.CASCADE
        ),
        ForeignKey(
            entity = CategoryEntity::class,
            parentColumns = ["id"],
            childColumns = ["categoryId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [
        Index("userId"),
        Index("categoryId"),
        Index("dateMillis"),
        Index("recurringSourceId")
    ]
)
data class ExpenseEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long,
    val categoryId: Long,
    val dateMillis: Long,
    val description: String,
    val amount: Double,
    val photoPath: String?,
    val isRecurring: Boolean = false,
    //This property links autogenerated expenses to the original expense its based on
    val recurringSourceId: Long? = null
)

@Entity(
    tableName = "budgets",
    foreignKeys = [ForeignKey(
        entity = UserEntity::class,
        parentColumns = ["id"],
        childColumns = ["userId"],
        onDelete = ForeignKey.CASCADE
    )],
    indices = [Index(value = ["userId"], unique = true)]
)
data class BudgetEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long,
    val maxSpend: Double,
    val minSave: Double
)

@Entity(
    tableName = "app_opens",
    foreignKeys = [ForeignKey(
        entity = UserEntity::class,
        parentColumns = ["id"],
        childColumns = ["userId"],
        onDelete = ForeignKey.CASCADE
    )],
    indices = [Index(value = ["userId", "dateKey"], unique = true)]
)
data class AppOpenEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long,
    val dateKey: String
)

@Entity(
    tableName = "badges_earned",
    foreignKeys = [ForeignKey(
        entity = UserEntity::class,
        parentColumns = ["id"],
        childColumns = ["userId"],
        onDelete = ForeignKey.CASCADE
    )],
    indices = [Index(value = ["userId", "badgeId"], unique = true)]
)
data class BadgeEarnedEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val userId: Long,
    val badgeId: String,
    val earnedAtTime: Long
)